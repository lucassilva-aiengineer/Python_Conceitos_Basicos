# Loops 
# Loops  ou laços de repetição são estruturas de códigos que repetem um bloco de código 
# uma quantidade de vezes epecíficadas, no caso dos loops whiles ditas por condições de 
# parada. 


# while loops executam um bloccódigo, iteram um códugo enquanto uma condição for cumprida. 


condicao = True

while condicao == True:
    print("A condição é verdedeira!")

    condicao = False 


# Construindo uma condição de parada impliícita 

contagem = 0 

while contagem < 10:
    print("A condição é verdadeira!")

    contagem += 1 

    